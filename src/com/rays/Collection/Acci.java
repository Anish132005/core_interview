package com.rays.Collection;

public class Acci {

	public static void main(String[] args) {

		for (char i = 'a'; i <= 'z'; i++) {
			System.out.println(i + "=" + (int) i);
		}
		
		System.out.println("===========================");

		for (char c = 'A'; c <= 'Z'; c++) {
			System.out.println(c + " = " + (int) c);
		}

		System.out.println("===========================");
		char i = '0';

		System.out.println(i + " = " + (int) i);

	}

}
